# 字面量

# 数字（number）:
# 整数（int）、浮点数（float）、复数（complex）、布尔值（bool）
666
13.14
3 + 5j
True

# 字符串（string）:
# 由任意数量的字符组成
"Hello, World!"

# 列表（list）:
# 有序、可变的序列
[1, 2, 3, 4, 5]
["apple", "banana", "cherry"]

# 元组（tuple）:
# 有序、不可变的序列
(1, 2, 3, 4, 5)
("apple", "banana", "cherry")

# 集合（set）:
# 无序、不重复的集合
{1, 2, 3, 4, 5}
{"apple", "banana", "cherry"}

# 字典（dict）:
# 无序key-value集合
{"name": "Alice", "age": 30, "city": "New York"}
{"fruit": "apple", "color": "red", "price": 1.2}

print("Hello, World!")
print(666)
print(13.14)